QUESTIONS_V3 = deepcopy(QUESTIONS_V2)
for index, question in enumerate(QUESTIONS_V3):
    question["id"] = f"V3Q{index + 1:02}"
    question["text"] = _CONTEXTS[index]
    question.pop("context", None)
    question.pop("prompt", None)
    if question["format"] == "bipolar":
        for option, label in zip(
            question["alternatives"], _ALTERNATIVES[index], strict=True
        ):
            option["label"] = label
    elif question["format"] == "choice":
        for option, label in zip(
            question["options"], _OPTIONS[index - 14], strict=True
        ):
            option["label"] = label
